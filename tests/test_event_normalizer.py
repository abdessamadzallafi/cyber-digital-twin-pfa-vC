class Test19SimulatedNetworkMetadata(unittest.TestCase):
    """Case 19: simulator IP/MAC are metadata, never a real network capture."""

    def setUp(self):
        self.e = _n({
            "device_id": "portique_P01", "type": "vibration", "value": 0.2,
            "timestamp": 19.0,
            "ip_src": "192.168.1.12", "mac_src": "AA:BB:CC:DD:EE:03", "port_src": 1883,
        })

    def test_ip_src_extracted(self):
        self.assertEqual(self.e.network.ip_src, "192.168.1.12")

    def test_mac_src_extracted(self):
        self.assertEqual(self.e.network.mac_src, "AA:BB:CC:DD:EE:03")

    def test_source_port_extracted(self):
        self.assertEqual(self.e.network.source_port, 1883)

    def test_observed_always_false(self):
        self.assertIs(self.e.network.observed, False)

    def test_simulated_always_true(self):
        self.assertIs(self.e.network.simulated, True)

    def test_observed_false_even_with_real_looking_ip(self):
        # Even if an IP looks real, the normalizer must never set observed=True
        e = _n({"device_id": "x", "type": "t", "timestamp": 19.0,
                "ip_src": "8.8.8.8", "mac_src": "FF:FF:FF:FF:FF:FF"})
