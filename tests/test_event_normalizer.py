class Test13TimestampAbsent(unittest.TestCase):
    """Case 13: when timestamp is missing the normalizer generates one."""

    def test_occurred_at_generated(self):
        before = time.time()
        e = _n({"device_id": "gate_01", "type": "barrier", "status": "closed"})
        after  = time.time()
        self.assertGreaterEqual(e.occurred_at, before)
        self.assertLessEqual(e.occurred_at, after)

    def test_two_calls_get_different_timestamps(self):
        p = {"device_id": "gate_01", "type": "barrier"}
        e1 = _n(p)
        time.sleep(0.01)
        e2 = _n(p)
        self.assertLessEqual(e1.occurred_at, e2.occurred_at)


