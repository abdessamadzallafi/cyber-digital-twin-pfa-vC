# TEST 16 — Exact conservation of raw_payload
# ===========================================================================

class Test16RawPayloadConservation(unittest.TestCase):
    """Case 16: raw_payload is an exact shallow copy, independent of the original."""

    def test_raw_payload_equals_original(self):
        p = _iot_payload()
        original_copy = dict(p)
        e = _n(p)
        self.assertEqual(e.raw_payload, original_copy)

    def test_raw_payload_is_a_copy_not_alias(self):
        p = _iot_payload()
        e = _n(p)
        self.assertIsNot(e.raw_payload, p)

    def test_mutating_original_does_not_affect_raw_payload(self):
        p = _iot_payload()
        e = _n(p)
        p["value"] = 999.0
        self.assertNotEqual(e.raw_payload.get("value"), 999.0)

    def test_mutating_raw_payload_does_not_affect_caller(self):
        p = _iot_payload()
        e = _n(p)
        e.raw_payload["value"] = 0.0
        # Original dict must be unchanged
        self.assertEqual(p["value"], 28.3)

    def test_extra_fields_present_in_raw_payload(self):
        p = _iot_payload(future_field="xyz")
        e = _n(p)
        self.assertEqual(e.raw_payload.get("future_field"), "xyz")


